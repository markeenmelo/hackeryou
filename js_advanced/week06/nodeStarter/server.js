// Require Express and make an express instance
const express = require('express')
const app = express()

// Enable CORS
app.use((req, res, next) => {
    res.setHeader('Access-Control-Allow-Origin', '*');
    next();
})

// Set the port
const port = process.env.PORT || 3500

// Iterate colors


// Endpoints
// create and endpoint that run on the root that returns a success message
app.get('/', (req, res) => {
    res.send({
        message: 'success'
    })
})

app.get('/randomcolor', (req, res) => {
    const randomNumber = Math.floor(Math.random() * app.colors.length)
    res.send({
        color: app.colors[randomNumber],
        status: 200
    })
})

app.get('/allcolors', (req, res) => {
    res.send({
        colors: app.colors,
        status: 200
    })
})

app.get('/index/:index', (req, res) => {
    const allColors = app.colors.map(color => {
        return Object.assign({}, {
            color: color,
            status: 200
        })
    })
    res.send(allColors[req.params.index])
})


// Make sure the app is listening in that port
app.listen(port)

